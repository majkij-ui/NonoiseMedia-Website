// TODO: link the cookie policy generated by CookieYes once the account exists.
// Leave null until then: the paragraph pointing to it renders only with a URL.
const COOKIE_POLICY_URL: string | null = null

const CONTACT_EMAIL = "contact@nonoise.media"

type PrivacySection = {
  id: string
  title: string
  paragraphs?: string[]
  items?: string[]
  after?: string[]
}

/** Turns the contact address inside a sentence into a mailto link. */
function withEmailLink(text: string) {
  const parts = text.split(CONTACT_EMAIL)
  return parts.map((part, i) => (
    <Fragment key={i}>
      {part}
      {i < parts.length - 1 ? (
        <a
          href={`mailto:${CONTACT_EMAIL}`}
          className="text-foreground underline decoration-white/30 underline-offset-4 transition-colors hover:decoration-foreground"
        >
          {CONTACT_EMAIL}
        </a>
      ) : null}
    </Fragment>
  ))
}

function Paragraphs({ items }: { items?: string[] }) {
  if (!items?.length) return null
  return items.map((text, i) => <p key={i}>{withEmailLink(text)}</p>)
}

export default async function PrivacyPage({
  params,
}: {
  params: Promise<{ locale: string }>
}) {
  const { locale } = await params
  setRequestLocale(locale)
  const t = await getTranslations("privacy")
  const tFooter = await getTranslations("footer")
  const sections = t.raw("sections") as PrivacySection[]

  return (
    <main className="relative min-h-screen w-full bg-background">
      <Navigation fixed />

      <section className="px-6 pb-16 pt-28 md:px-12 md:pb-24 md:pt-36">
        <div className="grid grid-cols-1 md:grid-cols-12">
          <div className="md:col-span-10 lg:col-span-8">
            <p className="mb-4 font-mono text-[10px] uppercase tracking-[0.2em] text-muted-foreground md:mb-6">
              {t("label")}
            </p>
            <h1 className="font-[family-name:var(--font-display)] text-5xl uppercase leading-[0.92] tracking-[0.02em] text-foreground sm:text-6xl md:text-7xl lg:text-8xl">
              {t("title")}
            </h1>
            <p className="mt-6 font-mono text-[10px] uppercase tracking-[0.2em] text-muted-foreground">
              {t("updated")}
            </p>
            <p className="mt-10 max-w-prose text-sm leading-relaxed text-foreground/80 md:text-base">
              {t("intro")}
            </p>
          </div>
        </div>
      </section>

      {sections.map((section, index) => (
        <section
          key={section.id}
          id={section.id}
          className="border-t border-white/20 px-6 py-12 md:px-12 md:py-16"
        >
          <div className="grid grid-cols-1 gap-6 md:grid-cols-12 md:gap-16">
            <div className="md:col-span-4">
              <p className="mb-3 font-mono text-[10px] uppercase tracking-[0.2em] text-muted-foreground">
                {String(index + 1).padStart(2, "0")}
              </p>
              <h2 className="max-w-xs font-[family-name:var(--font-display)] text-3xl uppercase leading-none tracking-[0.02em] text-foreground md:text-4xl">
                {section.title}
              </h2>
            </div>

            <div className="max-w-prose space-y-4 text-sm leading-relaxed text-foreground/70 md:col-span-8 md:text-base">
              <Paragraphs items={section.paragraphs} />

              {section.items?.length ? (
                <ul className="space-y-3 border-l border-white/20 pl-5">
                  {section.items.map((item, i) => (
                    <li key={i}>{withEmailLink(item)}</li>
                  ))}
                </ul>
              ) : null}

              <Paragraphs items={section.after} />

              {section.id === "cookies" ? (
                <>
                  {COOKIE_POLICY_URL ? (
                    <p>
                      {t("cookiePolicy")}{" "}
                      <a
                        href={COOKIE_POLICY_URL}
                        className="text-foreground underline decoration-white/30 underline-offset-4 transition-colors hover:decoration-foreground"
                      >
                        {t("cookiePolicyLink")}
                      </a>
                    </p>
                  ) : null}
                  <CookieSettingsLink className="font-mono text-xs uppercase tracking-[0.2em] text-foreground underline decoration-white/30 underline-offset-4 transition-colors hover:decoration-foreground" />
                </>
              ) : null}
            </div>
          </div>
        </section>
      ))}

      <footer className="flex flex-wrap items-center justify-end gap-x-6 gap-y-2 border-t border-white/20 px-6 py-8 text-xs tracking-widest text-muted-foreground md:px-12">
        <FooterLegalLinks />
        <span>{tFooter("copyright")}</span>
      </footer>
    </main>
  )
}
